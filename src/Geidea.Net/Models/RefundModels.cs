using System.Text.Json.Serialization;

namespace Geidea.Models
{
    /// <summary>
    /// Request body for the Refund API. Full or partial refunds are supported;
    /// cumulative refunds cannot exceed the paid amount.
    /// The client fills in <see cref="Timestamp"/> and <see cref="Signature"/> automatically.
    /// </summary>
    public class RefundRequest
    {
        /// <summary>Geidea order ID of the completed (paid/captured/settled) transaction.</summary>
        [JsonPropertyName("orderId")]
        public string OrderId { get; set; }

        /// <summary>HTTPS URL receiving the refund result. Optional.</summary>
        [JsonPropertyName("callbackUrl")]
        public string CallbackUrl { get; set; }

        /// <summary>Amount to refund. Must be &gt; 0.01 with at most two decimals.</summary>
        [JsonPropertyName("refundAmount")]
        public decimal RefundAmount { get; set; }

        /// <summary>Auto-generated by the client if not set — same value is used in the signature.</summary>
        [JsonPropertyName("timestamp")]
        public string Timestamp { get; set; }

        /// <summary>HMAC-SHA256 signature. Auto-generated by the client if not set.</summary>
        [JsonPropertyName("signature")]
        public string Signature { get; set; }
    }

    /// <summary>
    /// Response of the Refund API. The updated <see cref="Order"/> reflects the new
    /// detailed status (e.g. "PartiallyRefunded").
    /// </summary>
    public class RefundResponse : GeideaApiResponse
    {
        [JsonPropertyName("order")]
        public GeideaOrder Order { get; set; }
    }

    /// <summary>
    /// Response of the Cancel Order API. Only orders that have not completed payment can be cancelled.
    /// </summary>
    public class CancelOrderResponse : GeideaApiResponse
    {
        [JsonPropertyName("orderId")]
        public string OrderId { get; set; }
    }
}
