using System.Collections.Generic;
using System.Text.Json.Serialization;

namespace Geidea.Models
{
    /// <summary>
    /// Request body for creating a hosted-checkout payment session.
    /// The <see cref="GeideaClient"/> fills in <see cref="Timestamp"/> and <see cref="Signature"/> automatically.
    /// </summary>
    public class CreateSessionRequest
    {
        /// <summary>Total amount of the payment (e.g. 100.00). Serialized with two decimals.</summary>
        [JsonPropertyName("amount")]
        public decimal Amount { get; set; }

        /// <summary>ISO 4217 currency code (e.g. "EGP", "SAR", "AED").</summary>
        [JsonPropertyName("currency")]
        public string Currency { get; set; }

        /// <summary>
        /// Timestamp of session creation. Auto-generated by the client if not set —
        /// the same value is used when computing <see cref="Signature"/>.
        /// </summary>
        [JsonPropertyName("timestamp")]
        public string Timestamp { get; set; }

        /// <summary>Your own unique reference for this session (optional but recommended).</summary>
        [JsonPropertyName("merchantReferenceId")]
        public string MerchantReferenceId { get; set; }

        /// <summary>
        /// HMAC-SHA256 signature. Auto-generated by the client if not set.
        /// Set it manually only if you computed it yourself.
        /// </summary>
        [JsonPropertyName("signature")]
        public string Signature { get; set; }

        /// <summary>HTTPS URL Geidea calls with the payment result. Must start with https://</summary>
        [JsonPropertyName("callbackUrl")]
        public string CallbackUrl { get; set; }

        /// <summary>URL the customer is redirected to after the payment completes.</summary>
        [JsonPropertyName("returnUrl")]
        public string ReturnUrl { get; set; }

        /// <summary>Checkout page language: "en" (default) or "ar".</summary>
        [JsonPropertyName("language")]
        public string Language { get; set; }

        /// <summary>Payment operation: "Pay" (default), "Authorize", etc.</summary>
        [JsonPropertyName("paymentOperation")]
        public string PaymentOperation { get; set; }

        /// <summary>Save the card for future use (returns a tokenId in the callback).</summary>
        [JsonPropertyName("cardOnFile")]
        public bool? CardOnFile { get; set; }

        /// <summary>Token of a previously saved card — for tokenized payments.</summary>
        [JsonPropertyName("tokenId")]
        public string TokenId { get; set; }

        /// <summary>Customer details shown on the checkout page.</summary>
        [JsonPropertyName("customer")]
        public GeideaCustomer Customer { get; set; }

        /// <summary>Order line items (required by some payment methods like Tabby/Tamara).</summary>
        [JsonPropertyName("order")]
        public GeideaOrderDetails Order { get; set; }
    }

    public class GeideaCustomer
    {
        [JsonPropertyName("email")]
        public string Email { get; set; }

        [JsonPropertyName("phoneNumber")]
        public string PhoneNumber { get; set; }

        [JsonPropertyName("phonecountrycode")]
        public string PhoneCountryCode { get; set; }

        [JsonPropertyName("firstName")]
        public string FirstName { get; set; }

        [JsonPropertyName("lastName")]
        public string LastName { get; set; }

        [JsonPropertyName("address")]
        public GeideaCustomerAddress Address { get; set; }
    }

    public class GeideaCustomerAddress
    {
        [JsonPropertyName("billing")]
        public GeideaAddressDetail Billing { get; set; }

        [JsonPropertyName("shipping")]
        public GeideaAddressDetail Shipping { get; set; }
    }

    public class GeideaAddressDetail
    {
        [JsonPropertyName("country")]
        public string Country { get; set; }

        [JsonPropertyName("city")]
        public string City { get; set; }

        [JsonPropertyName("street")]
        public string Street { get; set; }

        [JsonPropertyName("postalCode")]
        public string PostalCode { get; set; }
    }

    public class GeideaOrderDetails
    {
        [JsonPropertyName("items")]
        public List<GeideaOrderItem> Items { get; set; }
    }

    public class GeideaOrderItem
    {
        [JsonPropertyName("merchantItemId")]
        public string MerchantItemId { get; set; }

        [JsonPropertyName("name")]
        public string Name { get; set; }

        [JsonPropertyName("description")]
        public string Description { get; set; }

        [JsonPropertyName("categories")]
        public string Categories { get; set; }

        [JsonPropertyName("count")]
        public int Count { get; set; }

        [JsonPropertyName("price")]
        public decimal Price { get; set; }

        [JsonPropertyName("sku")]
        public string Sku { get; set; }
    }
}
